"""Autonomous AI Librarian message, chat, and session state Pydantic schemas.

Defines schemas for multi-turn conversational interactions with the PydanticAI
agent powered by Claude Haiku, tool execution audits, and Human-in-the-Loop
interactive action cards.
"""

from typing import Any, Literal
from pydantic import BaseModel, Field


class AgentMessage(BaseModel):
    """Single message turn in the conversational chat history."""

    role: Literal["user", "assistant", "system"] = Field(
        ...,
        description="Sender role of the message",
    )
    content: str | None = Field(
        None,
        description="Text content of the message",
    )


class ToolExecutionRecord(BaseModel):
    """Audit record capturing an autonomous database tool invocation by the agent."""

    tool_name: str = Field(
        ...,
        description="Name of the invoked tool (e.g. search_catalog, check_availability, borrow_book)",
    )
    arguments: dict[str, Any] = Field(
        default_factory=dict,
        description="Input arguments passed to the tool by the model",
    )
    result: Any = Field(
        None,
        description="Output payload returned by the database tool function",
    )


class AgentChatRequest(BaseModel):
    """Request payload sent from the client chat interface to the AI Librarian."""

    message: str = Field(
        ...,
        min_length=1,
        max_length=2000,
        description="Patron natural language inquiry, search request, or confirmation",
    )
    history: list[AgentMessage] = Field(
        default_factory=list,
        description="Sequential list of prior message turns for multi-turn context",
    )


class AgentChatResponse(BaseModel):
    """Response envelope returned to the client chat interface."""

    reply: str = Field(
        ...,
        description="Conversational markdown response generated by Claude Haiku",
    )
    tools_executed: list[ToolExecutionRecord] = Field(
        default_factory=list,
        description="Audit trace of all tools executed during the ReAct loop",
    )
    interactive_card: dict[str, Any] | None = Field(
        default=None,
        description=(
            "Optional structured UI action card payload (e.g. CONFIRM_BORROW for "
            "Human-in-the-Loop checkout confirmation, BOOK_LIST for multi-candidate "
            "discovery decks, or ACTIVE_LOANS for patron loan overviews)"
        ),
    )

